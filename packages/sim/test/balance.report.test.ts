import { writeFileSync } from 'node:fs';
import { describe, it } from 'vitest';
import { loadContent } from '@dead-sector/content';
import {
  buildDebrief,
  GameSimulation,
  MISSION_PLANS,
  runPlan,
  STEALTH_PLAN,
  type PlanStep,
} from '../src';

/**
 * Multi-seed balance report (opt-in: `pnpm balance`). Plays each scripted route on several seeds
 * and writes docs/testing/balance.md. Scripted routes are fixed and cannot adapt, so these numbers
 * are a floor for a human player, useful to spot missions that are unwinnable or trivial.
 */
const SEEDS = 10;
const enabled = !!process.env['BALANCE_REPORT'];

describe.skipIf(!enabled)('balance report', () => {
  it('writes docs/testing/balance.md', () => {
    const content = loadContent();
    const runs: [string, string, PlanStep[]][] = [
      ['a-ultima-farmacia', 'furtiva', STEALTH_PLAN],
      ['a-ultima-farmacia', 'combate', MISSION_PLANS['a-ultima-farmacia']!],
      ['sinal-fraco', 'roteiro', MISSION_PLANS['sinal-fraco']!],
      ['plantao-noturno', 'roteiro', MISSION_PLANS['plantao-noturno']!],
    ];
    const rows: string[] = [];
    for (const [id, route, plan] of runs) {
      const base = content.missions[id]!.canonicalSeed;
      let wins = 0;
      let deaths = 0;
      let time = 0;
      const reasons: Record<string, number> = {};
      for (let i = 0; i < SEEDS; i++) {
        const sim = GameSimulation.create(id, base + i * 101, content);
        runPlan(sim, plan);
        const d = buildDebrief(sim.state);
        if (d.outcome !== 'failed') wins += 1;
        else reasons[d.reason ?? '?'] = (reasons[d.reason ?? '?'] ?? 0) + 1;
        deaths += d.survivors.filter((s) => s.status === 'dead' && s.squadId !== null).length;
        time += d.durationSeconds;
      }
      const fails = Object.entries(reasons)
        .map(([r, n]) => `${r} ×${n}`)
        .join(', ');
      rows.push(
        `| ${content.missions[id]!.displayName} | ${route} | ${wins}/${SEEDS} | ${(deaths / SEEDS).toFixed(1)} | ${Math.round(time / SEEDS)} s | ${fails || '—'} |`,
      );
    }
    const md = `# Balance report

Generated by \`pnpm balance\`: each scripted route on ${SEEDS} seeds (canonical seed + 101·k). The routes are fixed
scripts that never adapt (no retreats, no rerouting around a horde), so the win rate is a floor for a human player;
it is used to catch missions that are unwinnable or trivial, not as a difficulty rating.

| Mission | Route | Wins | Squad deaths (avg) | Duration (avg) | Failure reasons |
| ------- | ----- | ---- | ------------------ | -------------- | --------------- |
${rows.join('\n')}
`;
    writeFileSync(new URL('../../../docs/testing/balance.md', import.meta.url), md);
    console.log(md);
  });
});
